# 변수타입
# 변수 : 값을 저장하는 공간
# 숫자형타입(정수형, 실수형), 문자열타입, 불타입(bool)
# 나타내는 문자 : int, float, str, bool
# 정수형 - 1,2,3 소수점 없음
# 실수형 - 1.1, 2.2 같이 소수점이 있음
# 문자열 - "안녕", '111'
# 불타입 - True, False (true, false 같이 소문자는 안됨)

# type(변수) -> 결과 : int, float, str, bool 중 하나로 나옴

# 변수규칙
# 특수문자는 사용할 수 없음
# _ 는 가능
# a = 10
# _a = 10
# a_1 = 10
# 숫자가 제일 앞에 오는 것은 안됨
# 1_a = 10 -> 에러
a_1_2_b = 10 # 가능
aBBa = 1
Aa = 1
a111111 = 1

